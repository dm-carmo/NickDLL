void __fastcall cro_non_league_promotion(BYTE* _this)
{
	comp_stats* comp_data = (comp_stats*)get_loaded_league(CRO_THIRD_9CF());
	vector<cm3_clubs*> relegated_clubs = get_relegated_teams(CRO_THIRD_9CF());

	comp_stats* playoff_stage = (comp_stats*)comp_data->stages[0];
	WORD promoted_teams = 0;
	for (WORD i = 0; i < playoff_stage->n_teams; i++) {
		teams_seeded t = ((teams_seeded*)playoff_stage->teams_list)[i];
		if (t.f6 == 1) {
			cm3_clubs* promote = t.club;
			if (promote->ClubDivision && promote->ClubDivision != comp_data->competition_db) {
				promote_club_6830B0((BYTE*)promote, (DWORD)comp_data->competition_db, 1);
				promoted_teams++;
			}
		}
	}

	if (promoted_teams != relegated_clubs.size()) create_message_box("Error", "Promoted and relegated club count does not match for cro_third", false);

	for (unsigned int i = 0; i < relegated_clubs.size(); i++)
	{
		relegate_club_6831A0((BYTE*)relegated_clubs[i], (DWORD)get_comp(CRO_FOURTH_9CF()), 1);
	}
}

void __fastcall cro_fake_lower_relegation(BYTE* _this)
{
	vector<cm3_clubs*> d4_clubs = find_clubs_of_comp(CRO_FOURTH_9CF(), NATION_CROATIA_9CF());
	vector<cm3_clubs*> lower_clubs = find_clubs_of_comp(A_LOWER_9CF(), NATION_CROATIA_9CF());
	unsigned int num_to_swap = d4_clubs.size() / 8;
	if (lower_clubs.size() < num_to_swap) num_to_swap = lower_clubs.size();

	vector<cm3_clubs*> promoted_clubs = get_random_weighted_clubs(lower_clubs, num_to_swap, true);
	vector<cm3_clubs*> relegated_clubs = get_random_weighted_clubs(d4_clubs, num_to_swap, false);

	for (unsigned int j = 0; j < num_to_swap; j++) {
		cm3_clubs* clubToRelegate = relegated_clubs[j];
		cm3_clubs* clubToPromote = promoted_clubs[j];

		cm3_club_comps* topDivision = clubToRelegate->ClubDivision;
		cm3_club_comps* bottomDivision = clubToPromote->ClubDivision;
		relegate_club_6831A0((BYTE*)clubToRelegate, (DWORD)bottomDivision, 1);
		promote_club_6830B0((BYTE*)clubToPromote, (DWORD)topDivision, 1);
	}
}

char cro_first_update(BYTE* _this) {
	comp_stats* data = (comp_stats*)_this;
	data->f76 = 0;

	BYTE* cro_second = get_loaded_league(CRO_SECOND_9CF());
	BYTE* cro_third = get_loaded_league(CRO_THIRD_9CF());

	// All teams that were in D1 must be professional
	update_club_pro_status_68A980(_this, Professional, Relegated, -3, 1);
	update_club_pro_status_68A980(_this, Professional, -3, Relegated, 1);
	// All teams that were not relegated from D2 must be professional
	// All teams that were relegated from D2 must be semi-professional
	update_club_pro_status_68A980(cro_second, Professional, Relegated, -3, 1);
	update_club_pro_status_68A980(cro_second, SemiProfessional, -3, Relegated, 0);
	// All teams that were in D3 must be semi-professional
	update_club_pro_status_68A980(cro_third, SemiProfessional, Promoted, -3, 1);
	update_club_pro_status_68A980(cro_third, SemiProfessional, Promoted, -3, 0);
	update_club_pro_status_68A980(cro_third, SemiProfessional, -3, Champions, 1);
	update_club_pro_status_68A980(cro_third, SemiProfessional, -3, Promoted, 1);

	DWORD v1 = *(DWORD*)_this;
	(*(void(__thiscall**)(BYTE*, int))(v1 + 0xB0))(_this, 1);
	cro_non_league_promotion(_this);

	sub_687970(_this, 0);
	if (data->fixtures_table) {
		sub_9452CA_free(data->fixtures_table);
		data->fixtures_table = 0;
	}
	if (data->f8) sub_4A1C50((BYTE*)(data->f8), 1);
	long current = data->current_stage;
	if (current >= 0) {
		for (long i = 0; i <= current; i++) {
			DWORD stage = data->stages[i];
			if (stage) {
				DWORD v1 = *(DWORD*)stage;
				(DWORD*)(*(int(__thiscall**)(BYTE*, int a2))(v1))((BYTE*)stage, 1);
			}
			data->stages[i] = 0;
		}
	}
	data->year++;
	data->current_stage = -1;
	cro_first_subs(_this);
	AddTeams(_this);
	sub_6835C0(_this);
	sub_6827D0(_this, 0);
	(*(int(__thiscall**)(BYTE*))(v1 + 0x5C))(_this);

	v1 = *(DWORD*)cro_second;
	(*(int(__thiscall**)(BYTE*))(v1 + 0x8))(cro_second);

	v1 = *(DWORD*)cro_third;
	(*(int(__thiscall**)(BYTE*))(v1 + 0x8))(cro_third);

	sub_68AA80(_this);
	return sub_79CEE0((BYTE*)*b74340, (BYTE*)(data->competition_db));
}

